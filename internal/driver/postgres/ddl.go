package postgres

import (
	"strings"
)

// buildDDL renders the CREATE statement of a relation from catalog rows
// (see TableDDL). It is pure, so it is unit-tested with fixture rows.
//
// Tables: CREATE [UNLOGGED] TABLE with each column's format_type, COLLATE,
// DEFAULT / identity / generated expression and NOT NULL; serial columns
// (a nextval default on a sequence the column owns) become
// smallserial/serial/bigserial so that the DDL creates its own sequence;
// then the local constraints from pg_get_constraintdef (PK, UNIQUE,
// EXCLUDE, CHECK, FK) and PARTITION BY. Views use pg_get_viewdef,
// materialized views add WITH DATA. Then non-constraint indexes
// (pg_get_indexdef), triggers (pg_get_triggerdef) and COMMENT ON.
//
// Not included: ownership, GRANTs, row-level security, tablespaces,
// storage parameters, identity sequence options, inheritance, partitions
// (a partition is rendered as a plain table), foreign table servers and
// options, and the definitions of referenced types, sequences and
// functions.
func buildDDL(rel pgRel, cols []pgColumn, cons []pgConstraint, indexes, triggers []string) string {
	qualified := rel.QSchema + "." + rel.QName
	var b strings.Builder
	switch rel.Kind {
	case "v", "m":
		kw := "VIEW"
		if rel.Kind == "m" {
			kw = "MATERIALIZED VIEW"
		}
		b.WriteString("CREATE " + kw + " " + qualified + " AS\n")
		b.WriteString(strings.TrimRight(strings.TrimSpace(rel.ViewDef), ";"))
		if rel.Kind == "m" {
			b.WriteString("\nWITH DATA")
		}
		b.WriteString(";\n")
	default:
		if rel.Kind == "f" {
			b.WriteString("-- Foreign table: the server and its options are not included.\n")
		}
		b.WriteString("CREATE ")
		if rel.Persistence == "u" {
			b.WriteString("UNLOGGED ")
		}
		b.WriteString("TABLE " + qualified + " (")
		var items []string
		for _, c := range cols {
			items = append(items, columnDef(c))
		}
		for _, c := range cons {
			items = append(items, "CONSTRAINT "+c.QName+" "+c.Def)
		}
		if len(items) > 0 {
			b.WriteString("\n    " + strings.Join(items, ",\n    ") + "\n")
		}
		b.WriteString(")")
		if rel.PartKey != "" {
			b.WriteString(" PARTITION BY " + rel.PartKey)
		}
		b.WriteString(";\n")
	}

	if len(indexes)+len(triggers) > 0 {
		b.WriteString("\n")
	}
	for _, ix := range indexes {
		b.WriteString(ix + ";\n")
	}
	for _, t := range triggers {
		b.WriteString(t + ";\n")
	}

	var comments []string
	if rel.Comment != "" {
		comments = append(comments, "COMMENT ON "+relKeyword(rel.Kind)+" "+qualified+" IS "+literal(rel.Comment)+";")
	}
	for _, c := range cols {
		if c.Comment.Valid {
			comments = append(comments, "COMMENT ON COLUMN "+qualified+"."+c.QName+" IS "+literal(c.Comment.String)+";")
		}
	}
	if len(comments) > 0 {
		b.WriteString("\n" + strings.Join(comments, "\n") + "\n")
	}
	return b.String()
}

// columnDef renders one column of CREATE TABLE.
func columnDef(c pgColumn) string {
	typ := c.Type
	serial := c.serialType()
	if serial != "" {
		typ = serial
	}
	parts := []string{c.QName, typ}
	if c.QCollation != "" {
		parts = append(parts, "COLLATE "+c.QCollation)
	}
	switch {
	case c.Generated != "" && c.Default.Valid:
		kind := "STORED"
		if c.Generated == "v" {
			kind = "VIRTUAL"
		}
		parts = append(parts, "GENERATED ALWAYS AS ("+c.Default.String+") "+kind)
	case c.Identity == "a":
		parts = append(parts, "GENERATED ALWAYS AS IDENTITY")
	case c.Identity == "d":
		parts = append(parts, "GENERATED BY DEFAULT AS IDENTITY")
	case serial == "" && c.Default.Valid:
		parts = append(parts, "DEFAULT "+c.Default.String)
	}
	if !c.Nullable {
		parts = append(parts, "NOT NULL")
	}
	return strings.Join(parts, " ")
}

// relKeyword is the COMMENT ON object type of a relkind.
func relKeyword(kind string) string {
	switch kind {
	case "v":
		return "VIEW"
	case "m":
		return "MATERIALIZED VIEW"
	case "f":
		return "FOREIGN TABLE"
	}
	return "TABLE"
}

// literal quotes s as a string literal the way quote_literal does: quotes
// doubled, and E” with doubled backslashes when s has a backslash.
func literal(s string) string {
	q := "'" + strings.ReplaceAll(s, "'", "''") + "'"
	if strings.Contains(s, `\`) {
		return "E" + strings.ReplaceAll(q, `\`, `\\`)
	}
	return q
}
