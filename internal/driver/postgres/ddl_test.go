func ns(s string) sql.NullString { return sql.NullString{String: s, Valid: true} }

func TestBuildDDLTable(t *testing.T) {
	rel := pgRel{Kind: "r", Persistence: "u", QSchema: "s", QName: `"My T"`, Comment: "It's", PartKey: ""}
	cols := []pgColumn{
		{QName: "id", Type: "integer", TypName: "int4", Default: ns("nextval('s.t_id_seq'::regclass)"), OwnedSeq: true},
		{QName: "big", Type: "bigint", TypName: "int8", Default: ns("nextval('s.big_seq'::regclass)"), OwnedSeq: true, Nullable: true},
		{QName: "small", Type: "smallint", TypName: "int2", Default: ns("nextval('x'::regclass)"), OwnedSeq: true},
		{QName: "notowned", Type: "integer", TypName: "int4", Default: ns("nextval('shared'::regclass)"), Nullable: true},
		{QName: "ident", Type: "bigint", TypName: "int8", Identity: "a"},
		{QName: "ident2", Type: "integer", TypName: "int4", Identity: "d"},
		{QName: "g", Type: "numeric", Generated: "s", Default: ns("(a * 2)"), Nullable: true},
		{QName: "v", Type: "numeric", Generated: "v", Default: ns("(a * 3)"), Nullable: true},
		{QName: `"Name"`, Type: "text", QCollation: `pg_catalog."C"`, Default: ns("'x'::text"), Nullable: true, Comment: ns(`back\slash`)},
		{QName: "odd", Type: "text", TypName: "text", Default: ns("nextval('q'::regclass)"), OwnedSeq: true, Nullable: true},
	}
	cons := []pgConstraint{{QName: "t_pkey", Def: "PRIMARY KEY (id)"}, {QName: "c", Def: "CHECK ((g > 0))"}}
	got := buildDDL(rel, cols, cons, []string{"CREATE INDEX i ON s.\"My T\" USING btree (g)"}, []string{"CREATE TRIGGER tr AFTER INSERT ON s.\"My T\" FOR EACH ROW EXECUTE FUNCTION f()"})
	want := `CREATE UNLOGGED TABLE s."My T" (
    id serial NOT NULL,
    big bigserial,
    small smallserial NOT NULL,
    notowned integer DEFAULT nextval('shared'::regclass),
    ident bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    ident2 integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    g numeric GENERATED ALWAYS AS ((a * 2)) STORED,
    v numeric GENERATED ALWAYS AS ((a * 3)) VIRTUAL,
    "Name" text COLLATE pg_catalog."C" DEFAULT 'x'::text,
    odd text DEFAULT nextval('q'::regclass),
    CONSTRAINT t_pkey PRIMARY KEY (id),
    CONSTRAINT c CHECK ((g > 0))
);

CREATE INDEX i ON s."My T" USING btree (g);
CREATE TRIGGER tr AFTER INSERT ON s."My T" FOR EACH ROW EXECUTE FUNCTION f();

COMMENT ON TABLE s."My T" IS 'It''s';
COMMENT ON COLUMN s."My T"."Name" IS E'back\\slash';
`
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestBuildDDLOthers(t *testing.T) {
	for _, tc := range []struct {
		name string
		rel  pgRel
		cols []pgColumn
		want string
	}{
		{"view", pgRel{Kind: "v", QSchema: "s", QName: "v", ViewDef: " SELECT 1 AS x;", Comment: "c"},
			[]pgColumn{{QName: "x", Type: "integer", Nullable: true, Comment: ns("d")}},
			"CREATE VIEW s.v AS\nSELECT 1 AS x;\n\nCOMMENT ON VIEW s.v IS 'c';\nCOMMENT ON COLUMN s.v.x IS 'd';\n"},
		{"matview", pgRel{Kind: "m", QSchema: "s", QName: "m", ViewDef: "SELECT 1"}, nil,
			"CREATE MATERIALIZED VIEW s.m AS\nSELECT 1\nWITH DATA;\n"},
		{"partitioned", pgRel{Kind: "p", QSchema: "s", QName: "p", PartKey: "RANGE (d)"},
			[]pgColumn{{QName: "d", Type: "date"}},
			"CREATE TABLE s.p (\n    d date NOT NULL\n) PARTITION BY RANGE (d);\n"},
		{"foreign", pgRel{Kind: "f", QSchema: "s", QName: "f", Comment: "x"}, nil,
			"-- Foreign table: the server and its options are not included.\nCREATE TABLE s.f ();\n\nCOMMENT ON FOREIGN TABLE s.f IS 'x';\n"},
	} {
		if got := buildDDL(tc.rel, tc.cols, nil, nil, nil); got != tc.want {
			t.Errorf("%s: got:\n%q\nwant:\n%q", tc.name, got, tc.want)
		}
	}
	if relKeyword("m") != "MATERIALIZED VIEW" || relKeyword("r") != "TABLE" {
		t.Fatal("relKeyword")
	}
}

func TestTriggerType(t *testing.T) {
	for typ, want := range map[int][2]string{
		1 | 2 | 4:      {"BEFORE", "INSERT"},
		1 | 4 | 16:     {"AFTER", "INSERT OR UPDATE"},
		64 | 1 | 8:     {"INSTEAD OF", "DELETE"},
		32:             {"AFTER", "TRUNCATE"},
		2 | 4 | 8 | 16: {"BEFORE", "INSERT OR DELETE OR UPDATE"},
	} {
		if ti, ev := triggerType(typ); ti != want[0] || ev != want[1] {
			t.Errorf("triggerType(%d) = %q, %q", typ, ti, ev)
		}
	}
}

func TestColumnDetail(t *testing.T) {
	d, err := pgColumn{Name: "x", Type: "integer", TypName: "int4", Default: ns("nextval('s'::regclass)"), OwnedSeq: true, Enum: ns(`["a","b"]`)}.detail()
	if err != nil || !d.AutoIncrement || d.Default == nil || len(d.EnumValues) != 2 {
		t.Fatalf("detail = %+v, %v", d, err)
	}
	d, _ = pgColumn{Name: "g", Generated: "v", Default: ns("(a)"), Identity: "d"}.detail()
	if d.Generated != "VIRTUAL" || d.GenerationExpr == nil || d.Default != nil || d.Identity != "BY DEFAULT" || !d.AutoIncrement {
		t.Fatalf("detail = %+v", d)
	}
	if _, err := (pgColumn{Name: "e", Enum: ns("{bad")}).detail(); err == nil {
		t.Fatal("expected enum error")
	}
	if tableType("m") != "materialized view" || tableType("v") != "view" || tableType("p") != "table" {
		t.Fatal("tableType")
	}
}
