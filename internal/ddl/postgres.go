package ddl

import (
	"strings"
)

// pgColumnDef renders a new column.
func (p *plan) pgColumnDef(c column) string {
	parts := []string{p.q(c.name), c.typ}
	if c.gen != "" {
		parts = append(parts, "GENERATED ALWAYS AS ("+c.gen+") STORED")
	}
	if c.defSet && c.def != "" {
		parts = append(parts, "DEFAULT "+c.def)
	}
	if c.ch.Nullable != nil && !*c.ch.Nullable {
		parts = append(parts, "NOT NULL")
	}
	if c.ch.AutoIncrement != nil && *c.ch.AutoIncrement {
		parts = append(parts, "GENERATED BY DEFAULT AS IDENTITY")
	}
	return strings.Join(parts, " ")
}

func (p *plan) pgComment(target, text string) string {
	v := "NULL"
	if text != "" {
		v = p.lit(text)
	}
	return "COMMENT ON " + target + " IS " + v
}

func (p *plan) pgIndex(x index) string {
	var b strings.Builder
	b.WriteString("CREATE ")
	if x.ch.Unique {
		b.WriteString("UNIQUE ")
	}
	b.WriteString("INDEX " + p.q(x.ch.Name) + " ON " + p.table())
	if x.ch.Method != "" {
		b.WriteString(" USING " + x.ch.Method)
	}
	b.WriteString(" (" + strings.Join(x.cols, ", ") + ")")
	if x.pred != "" {
		b.WriteString(" WHERE " + x.pred)
	}
	return b.String()
}

func (p *plan) postgres() ([]Statement, error) {
	tc := p.in.Change
	t := p.table()
	var out []Statement
	add := func(section string, i int, sql string) { out = append(out, stmt(section, i, sql)) }

	if tc.Create {
		var defs []string
		for _, c := range p.cols {
			defs = append(defs, p.pgColumnDef(c))
		}
		if p.pk != nil && len(*p.pk) > 0 {
			defs = append(defs, "PRIMARY KEY ("+p.list(*p.pk)+")")
		}
		for _, x := range p.fks {
			defs = append(defs, p.fkClause(x))
		}
		for _, x := range p.checks {
			defs = append(defs, p.checkClause(x))
		}
		add(SectionTable, -1, "CREATE TABLE "+t+" (\n  "+strings.Join(defs, ",\n  ")+"\n)")
		for _, x := range p.idx {
			add(SectionIndexes, x.i, p.pgIndex(x))
		}
		if p.comment != nil && *p.comment != "" {
			add(SectionTable, -1, p.pgComment("TABLE "+t, *p.comment))
		}
		for _, c := range p.cols {
			if c.ch.Comment != nil && *c.ch.Comment != "" {
				add(SectionColumns, c.i, p.pgComment("COLUMN "+t+"."+p.q(c.name), *c.ch.Comment))
			}
		}
		return out, nil
	}

	// Drops.
	for _, x := range p.fks {
		if x.ch.Op == OpDrop {
			add(SectionFKs, x.i, "ALTER TABLE "+t+" DROP CONSTRAINT "+p.q(x.ch.Name))
		}
	}
	for _, x := range p.checks {
		if x.ch.Op == OpDrop {
			add(SectionChecks, x.i, "ALTER TABLE "+t+" DROP CONSTRAINT "+p.q(x.ch.Name))
		}
	}
	for _, x := range p.idx {
		if x.ch.Op != OpDrop {
			continue
		}
		if con, ok := p.in.Extra.ConstraintIndexes[x.ch.Name]; ok {
			add(SectionIndexes, x.i, "ALTER TABLE "+t+" DROP CONSTRAINT "+p.q(con))
		} else {
			add(SectionIndexes, x.i, "DROP INDEX "+p.q(tc.Schema)+"."+p.q(x.ch.Name))
		}
	}
	for i, name := range p.trigs {
		add(SectionTriggers, i, "DROP TRIGGER "+p.q(name)+" ON "+t)
	}
	if p.pk != nil && p.hasPK() && p.in.Extra.PKName != "" {
		add(SectionPK, -1, "ALTER TABLE "+t+" DROP CONSTRAINT "+p.q(p.in.Extra.PKName))
	}

	// Columns: drops, then changes (renames last, so the other changes use
	// the current name), then additions.
	for _, c := range p.cols {
		if c.ch.Op == OpDrop {
			add(SectionColumns, c.i, "ALTER TABLE "+t+" DROP COLUMN "+p.q(c.ch.Name))
		}
	}
	for _, c := range p.cols {
		if c.ch.Op != OpAlter {
			continue
		}
		col := t + " ALTER COLUMN " + p.q(c.ch.Name)
		if c.typ != "" {
			s := "ALTER TABLE " + col + " TYPE " + c.typ
			if c.using != "" {
				s += " USING " + c.using
			}
			add(SectionColumns, c.i, s)
		}
		if c.ch.AutoIncrement != nil && !*c.ch.AutoIncrement && c.cur.AutoIncrement {
			if c.cur.Identity != "" {
				add(SectionColumns, c.i, "ALTER TABLE "+col+" DROP IDENTITY")
			} else if !c.defSet {
				// serial: the sequence is the default.
				add(SectionColumns, c.i, "ALTER TABLE "+col+" DROP DEFAULT")
			}
		}
		if c.defSet {
			if c.def == "" {
				add(SectionColumns, c.i, "ALTER TABLE "+col+" DROP DEFAULT")
			} else {
				add(SectionColumns, c.i, "ALTER TABLE "+col+" SET DEFAULT "+c.def)
			}
		}
		if c.ch.Nullable != nil && *c.ch.Nullable != c.cur.Nullable {
			if *c.ch.Nullable {
				add(SectionColumns, c.i, "ALTER TABLE "+col+" DROP NOT NULL")
			} else {
				add(SectionColumns, c.i, "ALTER TABLE "+col+" SET NOT NULL")
			}
		}
		if c.ch.AutoIncrement != nil && *c.ch.AutoIncrement && !c.cur.AutoIncrement {
			add(SectionColumns, c.i, "ALTER TABLE "+col+" ADD GENERATED BY DEFAULT AS IDENTITY")
		}
		if c.ch.Comment != nil {
			add(SectionColumns, c.i, p.pgComment("COLUMN "+t+"."+p.q(c.ch.Name), *c.ch.Comment))
		}
		if c.name != c.ch.Name {
			add(SectionColumns, c.i, "ALTER TABLE "+t+" RENAME COLUMN "+p.q(c.ch.Name)+" TO "+p.q(c.name))
		}
	}
	for _, c := range p.cols {
		if c.ch.Op != OpAdd {
			continue
		}
		add(SectionColumns, c.i, "ALTER TABLE "+t+" ADD COLUMN "+p.pgColumnDef(c))
		if c.ch.Comment != nil && *c.ch.Comment != "" {
			add(SectionColumns, c.i, p.pgComment("COLUMN "+t+"."+p.q(c.name), *c.ch.Comment))
		}
	}

	// Additions.
	if p.pk != nil && len(*p.pk) > 0 {
		add(SectionPK, -1, "ALTER TABLE "+t+" ADD PRIMARY KEY ("+p.list(*p.pk)+")")
	}
	for _, x := range p.idx {
		switch x.ch.Op {
		case OpAdd:
			add(SectionIndexes, x.i, p.pgIndex(x))
		case OpRename:
			add(SectionIndexes, x.i, "ALTER INDEX "+p.q(tc.Schema)+"."+p.q(x.ch.Name)+" RENAME TO "+p.q(x.ch.NewName))
		}
	}
	for _, x := range p.fks {
		if x.ch.Op == OpAdd {
			add(SectionFKs, x.i, "ALTER TABLE "+t+" ADD "+p.fkClause(x))
		}
	}
	for _, x := range p.checks {
		if x.ch.Op == OpAdd {
			add(SectionChecks, x.i, "ALTER TABLE "+t+" ADD "+p.checkClause(x))
		}
	}
	if p.comment != nil {
		add(SectionTable, -1, p.pgComment("TABLE "+t, *p.comment))
	}
	if p.rename != "" {
		add(SectionTable, -1, "ALTER TABLE "+t+" RENAME TO "+p.q(p.rename))
	}
	return out, nil
}
