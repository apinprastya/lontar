// Package ddl changes the structure of tables: it validates a structured
// TableChange from the Structure view against fresh introspection and
// generates the engine's DDL.
//
// The frontend never sends DDL. Identifiers are looked up in the table's
// metadata (or are new names) and quoted with the dialect; literals
// (default values, comments, enum values) are quoted here. The only SQL
// the user writes are types, default/check/generated expressions, index
// expressions and partial-index predicates, and each is validated to be a
// single type or expression (see validate.go). DDL cannot bind
// parameters, so the preview shows exactly the statements Apply runs.
package ddl

import (
	"lontar/internal/driver"
)

// Change operations.
const (
	OpAdd    = "add"
	OpAlter  = "alter"
	OpDrop   = "drop"
	OpRename = "rename"
)

// Default kinds.
const (
	// DefaultNone removes the default (or adds a column without one).
	DefaultNone = "none"
	// DefaultNull is DEFAULT NULL.
	DefaultNull = "null"
	// DefaultValue is a literal, quoted by Go.
	DefaultValue = "value"
	// DefaultExpression is SQL written by the user (validated: one
	// expression).
	DefaultExpression = "expression"
)

// TableChange is everything staged for one table in the Structure view.
type TableChange struct {
	Schema string `json:"schema"`
	// Table is the existing table, or the new table's name with Create.
	Table string `json:"table"`
	// Create makes a new table from Columns, PrimaryKey, Indexes,
	// ForeignKeys, Checks and Comment.
	Create bool `json:"create"`
	// Base is the structure the change was made from (nil with Create).
	// Apply refuses when the table no longer matches it.
	Base *driver.TableDetail `json:"base"`

	// NewName renames the table; Comment sets its comment ("" removes it).
	NewName *string `json:"newName"`
	Comment *string `json:"comment"`

	Columns []ColumnChange `json:"columns"`
	// PrimaryKey replaces the primary key with these columns (in key
	// order); an empty list drops it. Nil leaves it alone.
	PrimaryKey   *[]string     `json:"primaryKey"`
	Indexes      []IndexChange `json:"indexes"`
	ForeignKeys  []FKChange    `json:"foreignKeys"`
	Checks       []CheckChange `json:"checks"`
	DropTriggers []string      `json:"dropTriggers"`
}

// Empty reports a change set without changes (a Create is never empty).
func (tc TableChange) Empty() bool {
	return !tc.Create && tc.NewName == nil && tc.Comment == nil && len(tc.Columns) == 0 && tc.PrimaryKey == nil &&
		len(tc.Indexes) == 0 && len(tc.ForeignKeys) == 0 && len(tc.Checks) == 0 && len(tc.DropTriggers) == 0
}

// TypeSpec is a column type. Text is the type as written ("varchar(255)",
// "numeric(10,2)", "text[]"); for MySQL/MariaDB enum and set, Text is
// "enum" or "set" and the values are in EnumValues (quoted by Go).
type TypeSpec struct {
	Text       string   `json:"text"`
	EnumValues []string `json:"enumValues"`
}

// DefaultSpec is a column default.
type DefaultSpec struct {
	Kind string `json:"kind"`
	Text string `json:"text"`
}

// GeneratedSpec makes a new column generated from Expr.
type GeneratedSpec struct {
	Expr   string `json:"expr"`
	Stored bool   `json:"stored"`
}

// ColumnChange adds, alters or drops a column. For alter, nil fields are
// left as they are.
type ColumnChange struct {
	Op string `json:"op"`
	// Name is the existing column (alter, drop) or the new one (add).
	Name string `json:"name"`
	// NewName renames the column (alter).
	NewName string `json:"newName"`

	Type     *TypeSpec    `json:"type"`
	Nullable *bool        `json:"nullable"`
	Default  *DefaultSpec `json:"default"`
	// Comment sets the comment ("" removes it).
	Comment *string `json:"comment"`
	// Collation (MySQL/MariaDB; "" means the table's default).
	Collation *string `json:"collation"`
	// AutoIncrement: PostgreSQL identity (GENERATED BY DEFAULT), MySQL
	// AUTO_INCREMENT. SQLite: only in CREATE TABLE, on an INTEGER
	// PRIMARY KEY.
	AutoIncrement *bool `json:"autoIncrement"`
	// Using converts the values on a PostgreSQL type change.
	Using *string `json:"using"`
	// Generated (add only).
	Generated *GeneratedSpec `json:"generated"`
}

// IndexColumn is one key part: a column, or an expression.
type IndexColumn struct {
	Column string `json:"column"`
	Expr   string `json:"expr"`
	Desc   bool   `json:"desc"`
	// Length is a MySQL/MariaDB prefix length (0: whole column).
	Length int `json:"length"`
}

// IndexChange adds, drops or renames an index.
type IndexChange struct {
	Op      string        `json:"op"`
	Name    string        `json:"name"`
	NewName string        `json:"newName"`
	Columns []IndexColumn `json:"columns"`
	Unique  bool          `json:"unique"`
	// Method: PostgreSQL btree/hash/gin/gist/brin/spgist; MySQL BTREE,
	// HASH, FULLTEXT, SPATIAL. "" is the engine default.
	Method string `json:"method"`
	// Predicate makes a partial index (PostgreSQL, SQLite).
	Predicate string `json:"predicate"`
}

// FKChange adds or drops a foreign key (changing one is drop + add).
type FKChange struct {
	Op         string   `json:"op"`
	Name       string   `json:"name"`
	Columns    []string `json:"columns"`
	RefSchema  string   `json:"refSchema"`
	RefTable   string   `json:"refTable"`
	RefColumns []string `json:"refColumns"`
	OnUpdate   string   `json:"onUpdate"`
	OnDelete   string   `json:"onDelete"`
}

// CheckChange adds or drops a check constraint.
type CheckChange struct {
	Op         string `json:"op"`
	Name       string `json:"name"`
	Expression string `json:"expression"`
}

// Sections of a change (ChangeError.Section, Statement.Section).
const (
	SectionTable    = "table"
	SectionColumns  = "columns"
	SectionPK       = "primaryKey"
	SectionIndexes  = "indexes"
	SectionFKs      = "foreignKeys"
	SectionChecks   = "checks"
	SectionTriggers = "triggers"
)

// Statement is one generated statement and the change it comes from.
type Statement struct {
	SQL     string `json:"sql"`
	Section string `json:"section"`
	// Index is the position of the change in its section (-1: the table).
	Index int `json:"index"`
}

// Result is the outcome of Apply.
type Result struct {
	Statements []Statement `json:"statements"`
}

// Failure kinds (ChangeError.Kind).
const (
	FailInvalid          = "invalid"
	FailUnsupported      = "unsupported"
	FailNotFound         = "not_found"
	FailStructureChanged = "structure_changed"
	FailReadOnly         = "readonly"
	FailDatabase         = "database"
)

// ChangeError says why a TableChange was refused or failed. Section,
// Index and Field name the change and field the UI highlights (Index -1:
// the table). Applied is how many statements had already run (MySQL and
// MariaDB commit each DDL statement; PostgreSQL and SQLite roll back, so
// it is 0 there).
type ChangeError struct {
	Kind    string `json:"kind"`
	Section string `json:"section"`
	Index   int    `json:"index"`
	Field   string `json:"field"`
	Message string `json:"message"`
	// SQL is the statement that failed (database errors).
	SQL     string `json:"sql"`
	Applied int    `json:"applied"`
	Err     error  `json:"-"`
}

func (e *ChangeError) Error() string { return e.Message }

// Unwrap returns the underlying error.
func (e *ChangeError) Unwrap() error { return e.Err }

func invalid(section string, index int, field, msg string) *ChangeError {
	return &ChangeError{Kind: FailInvalid, Section: section, Index: index, Field: field, Message: msg}
}

func unsupported(section string, index int, field, msg string) *ChangeError {
	return &ChangeError{Kind: FailUnsupported, Section: section, Index: index, Field: field, Message: msg}
}

func notFound(section string, index int, field, msg string) *ChangeError {
	return &ChangeError{Kind: FailNotFound, Section: section, Index: index, Field: field, Message: msg}
}
